'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
module.exports = async function smoke(win) {
  const js = code => win.webContents.executeJavaScript(code);
  const pause = ms => new Promise(r=>setTimeout(r,ms));
  await pause(400);
  assert.equal(await js('document.title'),'DB Tools · Folien-Zuschnittplaner');
  console.log('UI startup:', await js('({welcome:document.getElementById("welcome").open, desktop:typeof desktop, saved:localStorage.getItem("db-tools-welcome-v1"),ready:document.readyState})'));
  assert.equal(await js('document.getElementById("welcome").open'),true);
  assert.equal(await js('typeof require'),'undefined');
  const folder=process.env.DB_TOOLS_QA_DIR || path.resolve('qa');
  fs.mkdirSync(folder,{recursive:true});
  const screenshot=async name=>{win.webContents.invalidate();await pause(150);fs.writeFileSync(path.join(folder,name),(await win.webContents.capturePage()).toPNG());};
  await screenshot('willkommen.png');
  await js('document.getElementById("start-example").click()');
  await pause(500);
  assert.equal(await js('document.getElementById("results").hidden'),false);
  assert.equal(await js('document.querySelectorAll("#partRows tr").length'),10);
  const persisted=await js('localStorage.getItem("dbs-zuschnitt-v2")');
  await screenshot('zuschnittplan.png');
  await win.webContents.reload();
  await new Promise(r=>win.webContents.once('did-finish-load',r));
  await pause(300);
  assert.equal(await js('document.getElementById("welcome").open'),false);
  assert.equal(await js('localStorage.getItem("dbs-zuschnitt-v2")'),persisted);
  assert.equal(await js('document.querySelectorAll("#rows tr").length'),4);
  await js('document.getElementById("calculate").click()'); await pause(300);
  await js('document.querySelector("#rows input").value="Geändert";document.querySelector("#rows input").dispatchEvent(new Event("input",{bubbles:true}))');
  assert.equal(await js('document.getElementById("results").hidden'),true);
  await js('document.getElementById("settings-button").click()'); await pause(300);
  assert.equal(await js('document.getElementById("preferences").open'),true);
  assert.match(await js('document.getElementById("update-message").textContent'),/signiert/);
  await js('document.getElementById("automatic-updates").checked=false;document.getElementById("save-settings").click()'); await pause(300);
  assert.equal((await js('desktop.settings()')).automatic,false);
  await screenshot('updates.png');
  await js('document.getElementById("close-preferences").click();document.getElementById("clear").click();document.getElementById("calculate").click()'); await pause(200);
  assert.match(await js('document.getElementById("error").textContent'),/mindestens/);
  // Exercise SVG/CSV handlers without opening a save dialog.
  await js('document.getElementById("example").click();document.getElementById("calculate").click()'); await pause(300);
  await js('window.testExports=[];download=(name,text,type)=>testExports.push({name,text,type});document.getElementById("csv").click();document.getElementById("svg").click()');
  const exports=await js('window.testExports');
  assert.match(exports[0].text,/Küchenfront/);assert.match(exports[1].text,/<svg/);
  const pdf=await win.webContents.printToPDF({printBackground:true,pageSize:'A4'});
  assert.ok(pdf.length>1000);
  fs.writeFileSync(path.join(folder,'zuschnittplan-test.pdf'),pdf);
  return {ok:true,checks:['Willkommen','Sandbox','10 Beispielteile','Speicherung nach Neuladen','Geänderte Eingaben','GitHub-Update-Einstellungen','Ungültige Eingaben','CSV','SVG','PDF'],screenshots:folder};
};
