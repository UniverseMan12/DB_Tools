'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
module.exports = async function smoke(win) {
  const js = code => win.webContents.executeJavaScript(code);
  const pause = ms => new Promise(r=>setTimeout(r,ms));
  await pause(400);
  assert.equal(await js('document.title'),'DB Tools · Folien-Zuschnittplaner');
  console.log('UI startup:', await js('({welcome:document.getElementById("welcome").open, desktop:typeof desktop, saved:localStorage.getItem("db-tools-welcome-v1"),ready:document.readyState})'));
  assert.equal(await js('document.getElementById("welcome").open'),true);
  assert.equal(await js('typeof require'),'undefined');
  const folder=process.env.DB_TOOLS_QA_DIR || path.resolve('qa');
  fs.mkdirSync(folder,{recursive:true});
  const screenshot=async name=>{await js('document.getAnimations().filter(a=>a.effect.getComputedTiming().iterations!==Infinity).forEach(a=>a.finish())');win.webContents.invalidate();await pause(150);fs.writeFileSync(path.join(folder,name),(await win.webContents.capturePage()).toPNG());};
  await screenshot('willkommen.png');
  await js('document.getElementById("start-example").click()');
  await pause(500);
  assert.equal(await js('document.getElementById("results").hidden'),false);
  assert.equal(await js('document.querySelectorAll("#partRows tr").length'),10);
  const persisted=await js('localStorage.getItem("dbs-zuschnitt-v2")');
  await screenshot('zuschnittplan.png');
  await win.webContents.reload();
  await new Promise(r=>win.webContents.once('did-finish-load',r));
  await pause(300);
  assert.equal(await js('document.getElementById("welcome").open'),false);
  assert.equal(await js('localStorage.getItem("dbs-zuschnitt-v2")'),persisted);
  assert.equal(await js('document.querySelectorAll("#rows tr").length'),4);
  await js('document.getElementById("calculate").click()'); await pause(300);
  await js('document.querySelector("#rows input").value="Geändert";document.querySelector("#rows input").dispatchEvent(new Event("input",{bubbles:true}))');
  assert.equal(await js('document.getElementById("results").hidden'),true);
  await js('document.getElementById("settings-button").click()'); await pause(300);
  assert.equal(await js('document.getElementById("preferences").open'),true);
  await js('document.querySelector("[data-theme-option=dark]").click()');
  assert.equal(await js('document.documentElement.dataset.theme'),'dark');
  await screenshot('einstellungen-dunkel.png');
  await js('document.querySelector("[data-theme-option=light]").click()');
  assert.equal(await js('document.documentElement.dataset.theme'),'light');
  await screenshot('einstellungen-hell.png');
  await js('document.querySelector("[data-theme-option=dark]").click();document.querySelector("[data-accent=teal]").click();document.getElementById("pref-compact").click()');
  assert.equal(await js('document.documentElement.dataset.accent'),'teal');
  assert.equal(await js('document.documentElement.dataset.density'),'compact');
  await js('document.getElementById("pref-motion").click()');
  assert.equal(await js('document.documentElement.dataset.motion'),'reduced');
  await js('document.querySelector("[data-tab=updates]").click()');
  assert.match(await js('document.getElementById("update-message").textContent'),/Sparkle|Updates|Version/);
  await js('document.getElementById("automatic-updates").click()'); await pause(300);
  assert.equal((await js('desktop.settings()')).automatic,false);
  await screenshot('updates.png');
  await js('document.getElementById("close-preferences").click();document.getElementById("clear").click();document.getElementById("calculate").click()'); await pause(200);
  assert.match(await js('document.getElementById("error").textContent'),/mindestens/);
  // Exercise SVG/CSV handlers without opening a save dialog.
  await js('document.getElementById("example").click();document.getElementById("calculate").click()'); await pause(300);
  await js('window.testExports=[];download=(name,text,type)=>testExports.push({name,text,type});document.getElementById("csv").click();document.getElementById("svg").click();document.getElementById("export-project").click()');
  const exports=await js('window.testExports');
  assert.match(exports[0].text,/Küchenfront/);assert.match(exports[1].text,/<svg/);
  assert.equal(JSON.parse(exports[2].text).format,'db-tools-project');
  await js('document.getElementById("clear").click();var transfer=new DataTransfer();transfer.items.add(new File([testExports[2].text],"projekt.json",{type:"application/json"}));document.getElementById("project-file").files=transfer.files;document.getElementById("project-file").dispatchEvent(new Event("change"))');await pause(200);
  assert.equal(await js('document.getElementById("confirm-dialog").open'),true);
  await js('document.getElementById("confirm-accept").click()');await pause(300);
  assert.equal(await js('document.querySelectorAll("#partRows tr").length'),10);
  await screenshot('zuschnittplan-dunkel.png');
  await js('document.getElementById("theme-toggle").click()');
  await screenshot('zuschnittplan-hell.png');
  await js('document.getElementById("command-button").click()');
  assert.equal(await js('document.getElementById("command-palette").open'),true);
  await js('document.getElementById("command-palette").close()');
  const pdf=await win.webContents.printToPDF({printBackground:true,pageSize:'A4'});
  assert.ok(pdf.length>1000);
  fs.writeFileSync(path.join(folder,'zuschnittplan-test.pdf'),pdf);
  return {ok:true,checks:['Animierter Einstieg','Sandbox','10 Beispielteile','Speicherung nach Neuladen','Hell- und Dunkelmodus','Akzentfarben','Kompakte Ansicht','Reduzierte Bewegung','GitHub-Update-Einstellungen','Projekt-Export und Import','Schnellaktionen','Ungültige Eingaben','CSV','SVG','PDF'],screenshots:folder};
};
